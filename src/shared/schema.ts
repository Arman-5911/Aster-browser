export const settingsSchema = z.object({
  autoSleep:z.boolean().default(false),sleepMinutes:z.number().int().min(5).max(120).default(15),
  tasks:z.array(z.object({id:z.string().uuid(),text:z.string().trim().min(1).max(200),done:z.boolean()}).strict()).max(100).default([]),
  wallpaperAssets:z.array(wallpaperAsset).max(8).default([]),
  siteStudios:z.array(z.object({origin:z.string().max(2048).refine(v=>websiteOrigin(v)===v),studio:studioSchema}).strict()).max(30).refine(v=>new Set(v.map(p=>p.origin)).size===v.length).default([]),
  studio:studioSchema.default(()=>studioSchema.parse({})),
  workspaceStudios:z.record(z.string().min(1).max(100).regex(/^[a-zA-Z0-9-]+$/),studioSchema).refine(v=>Object.keys(v).length<=20).default({}),
  theme: z.enum(['light', 'dark', 'system']).default('light'),
  accent: z.enum(['forest', 'slate', 'clay']).default('forest'),
  density: z.enum(['comfortable', 'compact']).default('comfortable'),
  searchEngine: z.enum(['duckduckgo', 'google', 'bing']).default('duckduckgo'),
  home: z.string().max(2048).refine(v => v === 'aster://newtab' || /^https?:\/\//i.test(v)).default('aster://newtab'),
  recordHistory: z.boolean().default(true),
  showBookmarks: z.boolean().default(true),
  startTitle:z.string().trim().min(1).max(80).default('A little space to explore.'),
  startBackground:z.enum(['plain','sage','sand','aurora']).default('plain'),
  tabStyle:z.enum(['classic','soft','pill']).default('soft'),
  tabWidth:z.number().int().min(140).max(280).default(204),
  tabFontSize:z.number().int().min(10).max(15).default(11),
  tabColor:z.string().regex(/^#[0-9a-fA-F]{6}$/).nullable().default(null),
  tabClose:z.enum(['always','hover']).default('always'),
  motion:z.enum(['off','calm','expressive']).default('calm'),
  wallpaper:z.string().uuid().nullable().default(null),
  wallpaperShade:z.number().int().min(50).max(95).default(78),
  wallpaperBlur:z.number().int().min(0).max(50).default(0),
  showRecent:z.boolean().default(true),
  quickLinks:z.array(z.object({name:z.string().trim().min(1).max(30),url:z.string().max(2048).refine(v=>{try{const u=new URL(v);return ['http:','https:'].includes(u.protocol)&&!u.username&&!u.password;}catch{return false;}})}).strict()).max(8).default([{name:'GitHub',url:'https://github.com'},{name:'Wikipedia',url:'https://wikipedia.org'},{name:'YouTube',url:'https://youtube.com'}]),
  readerFont:z.enum(['serif','sans']).default('serif'),
  readerSize:z.number().int().min(16).max(28).default(20),
  readerWidth:z.enum(['narrow','wide']).default('narrow'),
  tabLayout: z.enum(['horizontal','vertical']).default('horizontal'),
  sidebarVisible: z.boolean().default(false),
  restoreOnStartup: z.boolean().default(true),
  aiSiteCompatibility:z.boolean().default(true),
  protection: protectionSchema.default('standard')
  ,vaultLockMinutes:z.number().int().min(1).max(30).default(5),secretClipboardSeconds:z.number().int().min(0).max(120).default(30)
}).strict();
const id = z.string().min(1).max(100);
